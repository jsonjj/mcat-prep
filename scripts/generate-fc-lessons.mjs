/**
 * Maps every V3 lesson to the single Foundational Concept the diagnostic reports
 * it under, so the production engine can bucket a question by its lesson.
 *
 * Questions carry `cluster`, `kc_id` and `lesson_id` but no FC, so the chain is
 * question -> lesson_id -> this table. It is the one piece the FC axis was
 * missing: `fc-axis.generated.ts` supplies the weights and
 * `bank-profiles.generated.ts` the counts, but neither says which bucket a given
 * question belongs to.
 *
 * MULTI-FC RULE — the lesson's FIRST listed concept, so the table is a true
 * partition of the FC-tagged lessons.
 *
 * Nine of the 114 lessons carry more than one FC. Duplicating them (which is
 * what the fc-10 column of bank-profiles.generated.ts does, and what
 * generate-fc-axis.mjs does for weights) is defensible when you are counting a
 * bank, but not when you are delivering one: a duplicated question could be
 * drawn twice in a sitting, once per bucket, and the per-bucket allocation
 * guarantee would be counting the same evidence twice. First-listed is also
 * exactly the tie-break the fc-15 composite already uses, so the shipped map and
 * the swept fc-15 profile agree bucket-for-bucket.
 *
 * The rule is cross-checked against `atlas-region-groups.json`, which was
 * grouped off the same axis and states the same rule in its own
 * `assignment_rule` field ("primary FC = first FC token in the lesson's FC
 * field"). A disagreement means the manifest and the atlas have drifted apart
 * and is a hard failure here rather than a silent divergence between the
 * diagnostic and the Progress brain.
 *
 * Lessons with no FC tag are omitted. Every question beneath them is out of the
 * diagnostic's scope, which the bank reports as a count rather than dropping
 * quietly.
 *
 * Run: node scripts/generate-fc-lessons.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const MANIFEST = 'curriculum/v3/v3-lesson-authoring-manifest.json';
const ATLAS = 'packages/contracts/src/atlas-region-groups.json';
const OUT = 'packages/policies/src/data/fc-lessons.generated.ts';

const FCS = Array.from({ length: 10 }, (_, i) => `FC${i + 1}`);

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
const atlas = JSON.parse(readFileSync(ATLAS, 'utf8'));

/** lesson -> the atlas's own primary FC (its `fc` field is a space-separated list). */
const atlasPrimary = new Map();
for (const region of atlas.regions) {
  for (const lesson of region.lessons ?? []) {
    const first = String(lesson.fc ?? '').trim().split(/\s+/)[0];
    if (first) atlasPrimary.set(lesson.lesson_id, first);
  }
}
if (atlasPrimary.size === 0) throw new Error(`no lesson FC tags found in ${ATLAS}`);

const assigned = [];
const untagged = [];
let multi = 0;

for (const lesson of manifest.curriculum.lessons) {
  const fcs = lesson.foundational_concepts ?? [];
  for (const fc of fcs) {
    if (!FCS.includes(fc)) throw new Error(`lesson ${lesson.lesson_id} carries unknown concept ${fc}`);
  }
  if (fcs.length === 0) {
    untagged.push(lesson.lesson_id);
    continue;
  }
  if (fcs.length > 1) multi += 1;

  const primary = fcs[0];
  const cross = atlasPrimary.get(lesson.lesson_id);
  if (cross !== undefined && cross !== primary) {
    throw new Error(
      `lesson ${lesson.lesson_id}: manifest primary FC ${primary} disagrees with the atlas's ${cross}`,
    );
  }
  assigned.push([lesson.lesson_id, primary]);
}

assigned.sort((a, b) => (a[0] < b[0] ? -1 : 1));
untagged.sort();

const byFc = new Map(FCS.map((fc) => [fc, 0]));
for (const [, fc] of assigned) byFc.set(fc, byFc.get(fc) + 1);
const empty = FCS.filter((fc) => byFc.get(fc) === 0);
if (empty.length > 0) {
  throw new Error(`no lesson maps to ${empty.join(', ')}; the FC axis would have an empty bucket`);
}

console.log(`lessons ${manifest.curriculum.lessons.length}: ${assigned.length} mapped, ${untagged.length} untagged`);
console.log(`multi-FC lessons resolved to their first listed concept: ${multi}`);
console.log('fc     lessons');
for (const fc of FCS) console.log(`  ${fc.padEnd(5)}${String(byFc.get(fc)).padStart(6)}`);

const body = assigned.map(([lessonId, fc]) => `  '${lessonId}': '${fc}',`).join('\n');
const untaggedBody = untagged.map((lessonId) => `  '${lessonId}',`).join('\n');

writeFileSync(
  OUT,
  `// GENERATED by scripts/generate-fc-lessons.mjs — do not edit by hand.
//
// Lesson -> Foundational Concept, for the ${assigned.length} of ${manifest.curriculum.lessons.length} V3 lessons that carry an FC
// tag. This is how a question reaches a diagnostic bucket: question.lesson_id
// -> here. ${multi} lessons carry several concepts and are resolved to their first
// listed one, which keeps this a true partition and matches both the fc-15
// tie-break in bank-profiles.generated.ts and the atlas's own assignment rule
// (the generator fails if those two disagree).
//
// The remaining ${untagged.length} lessons carry no FC at all. Their questions — all of the
// reasoning and CARS bank — are out of the diagnostic's scope entirely; see
// FC_UNTAGGED_LESSONS.

export const FC_LESSON: Readonly<Record<string, string>> = {
${body}
};

/**
 * Lessons with no Foundational Concept. Kept so the exclusion the diagnostic
 * makes is inspectable rather than an absence from the table above.
 */
export const FC_UNTAGGED_LESSONS: readonly string[] = [
${untaggedBody}
];
`,
  'utf8',
);
console.log(`\nwrote ${OUT}`);
