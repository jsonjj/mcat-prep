/**
 * Derives each skill cluster's prerequisite-unlock weight from the V3 registry
 * graph, replacing a hand-tuned table with the real edge structure.
 *
 * "Unlock" = how much of the rest of the curriculum becomes reachable once a
 * cluster's knowledge components are in place. We walk the directed
 * prerequisite edges transitively and count how many downstream units in OTHER
 * clusters each cluster gates. Weights are normalised so the most unlocking
 * cluster scores 1.0.
 *
 * Run: node scripts/generate-unlock-weights.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const MANIFEST = 'curriculum/v3/v3-lesson-authoring-manifest.json';
const ATLAS = 'packages/contracts/src/atlas.ts';
const OUT = 'packages/policies/src/data/unlock-weights.generated.ts';

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));

// lesson -> cluster, read from the baked client-safe atlas map.
const atlasSource = readFileSync(ATLAS, 'utf8');
const lessonCluster = new Map();
for (const m of atlasSource.matchAll(/'(V3-LES-\d+)':\s*'([A-Z]+\d)'/g)) {
  lessonCluster.set(m[1], m[2]);
}
if (lessonCluster.size === 0) throw new Error('no lesson->cluster pairs found in atlas.ts');

// node -> cluster, for both KCs and capstones (both carry owning_lesson_id).
const nodeCluster = new Map();
for (const kc of manifest.curriculum.kcs) {
  const c = lessonCluster.get(kc.owning_lesson_id);
  if (c) nodeCluster.set(kc.kc_id, c);
}
for (const cap of manifest.curriculum.capstones ?? []) {
  const c = lessonCluster.get(cap.owning_lesson_id);
  if (c) nodeCluster.set(cap.capstone_id, c);
}

// Directed prerequisite edges only: these are the ones that actually gate.
const PREREQ = new Set(['HARD_PREREQUISITE', 'HELPFUL_PREREQUISITE']);
const adjacency = new Map();
let edgeCount = 0;
for (const e of manifest.graph.edges) {
  if (!PREREQ.has(e.edge_type) || e.directionality !== 'directed') continue;
  if (!adjacency.has(e.source_id)) adjacency.set(e.source_id, []);
  adjacency.get(e.source_id).push(e.target_id);
  edgeCount += 1;
}

/** All nodes transitively downstream of `start`. */
const downstream = (start) => {
  const seen = new Set();
  const queue = [...(adjacency.get(start) ?? [])];
  while (queue.length > 0) {
    const n = queue.pop();
    if (seen.has(n)) continue;
    seen.add(n);
    for (const next of adjacency.get(n) ?? []) if (!seen.has(next)) queue.push(next);
  }
  return seen;
};

const CLUSTERS = ['R1','R2','R3','CP1','CP2','CP3','BB1','BB2','BB3','BB4','PS1','PS2','PS3','CA1','CA2'];
const reach = new Map(CLUSTERS.map((c) => [c, new Set()]));
for (const [node, cluster] of nodeCluster) {
  if (!reach.has(cluster)) continue;
  for (const target of downstream(node)) {
    // Only count unlocking of OTHER clusters: that is what "fixing this also
    // helps that" means for a learner choosing where to start.
    if (nodeCluster.get(target) !== cluster) reach.get(cluster).add(target);
  }
}

const counts = CLUSTERS.map((c) => [c, reach.get(c).size]);
const max = Math.max(...counts.map(([, n]) => n), 1);

console.log(`edges used: ${edgeCount}  nodes mapped: ${nodeCluster.size}`);
console.log('cluster  downstream-in-other-clusters  weight');
for (const [c, n] of [...counts].sort((a, b) => b[1] - a[1])) {
  console.log(`  ${c.padEnd(4)} ${String(n).padStart(4)}   ${(n / max).toFixed(3)}`);
}

const body = CLUSTERS.map((c) => {
  const n = reach.get(c).size;
  return `  ${c}: ${(n / max).toFixed(3)},`;
}).join('\n');

writeFileSync(
  OUT,
  `// GENERATED by scripts/generate-unlock-weights.mjs — do not edit by hand.
//
// Prerequisite-unlock weight per skill cluster, derived from the V3 registry
// graph (${edgeCount} directed HARD/HELPFUL_PREREQUISITE edges over
// ${nodeCluster.size} mapped units). The value is the count of downstream units
// in OTHER clusters that the cluster transitively gates, normalised so the most
// unlocking cluster is 1.0.
//
// NOT YET ADOPTED — see UNLOCK_WEIGHT in ../diagnostic.ts. The registry graph is
// still too sparse for this to be trustworthy: only 149 of 422 KCs carry any
// outgoing edge, and just 81 directed edges cross cluster boundaries, which is
// the only structure that matters here. The resulting table leaves most
// clusters at zero. Kept generated and in-repo so the switch is a one-line
// change once the graph is populated and learner-validated.
import type { SkillCluster } from '@mcat/contracts';

export const GENERATED_UNLOCK_WEIGHT: Readonly<Record<SkillCluster, number>> = {
${body}
};
`,
  'utf8',
);
console.log(`\nwrote ${OUT}`);
